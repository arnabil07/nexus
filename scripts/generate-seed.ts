/**
 * Generates supabase/seed.sql from the local content files in /data.
 * Run with:  npm run db:seed-sql
 * Then paste supabase/seed.sql into the Supabase SQL editor and run it.
 * It is safe to run repeatedly: existing rows are updated ("upsert").
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { learningPaths } from "../data/learning-paths";
import { projects } from "../data/projects";
import { resources } from "../data/resources";
import { topics } from "../data/topics";

type Value = string | number | boolean | null | undefined | string[] | object;

function sql(value: Value): string {
  if (value === null || value === undefined) return "null";
  if (typeof value === "number") return String(value);
  if (typeof value === "boolean") return value ? "true" : "false";
  if (Array.isArray(value) && value.every((v) => typeof v === "string")) {
    return value.length ? `array[${value.map((v) => sql(v)).join(", ")}]::text[]` : "'{}'::text[]";
  }
  if (typeof value === "object") return `${sql(JSON.stringify(value))}::jsonb`;
  return `'${String(value).replace(/'/g, "''")}'`;
}

function upsert(table: string, rows: Record<string, Value>[], conflict: string[]): string {
  if (!rows.length) return "";
  const columns = Object.keys(rows[0]);
  const updates = columns.filter((c) => !conflict.includes(c)).map((c) => `${c} = excluded.${c}`);
  const values = rows.map((row) => `  (${columns.map((c) => sql(row[c])).join(", ")})`).join(",\n");
  return `insert into public.${table} (${columns.join(", ")}) values\n${values}\non conflict (${conflict.join(", ")}) ${
    updates.length ? `do update set ${updates.join(", ")}` : "do nothing"
  };\n\n`;
}

let out = `-- NEXUS seed data — generated by scripts/generate-seed.ts on ${new Date().toISOString()}\n`;
out += "-- Do not edit by hand: edit /data and run `npm run db:seed-sql` again.\n\nbegin;\n\n";

out += upsert(
  "topics",
  topics.map((t, i) => ({
    slug: t.slug,
    title: t.title,
    category: t.category,
    icon: t.icon,
    summary: t.summary,
    level: t.level,
    beginner_friendly: t.beginnerFriendly,
    popular: Boolean(t.popular),
    introduction: t.introduction,
    what_you_will_learn: t.whatYouWillLearn,
    applications: t.applications,
    prerequisites: t.prerequisites,
    core_concepts: t.coreConcepts,
    roadmap: t.roadmap,
    related: t.related,
    sort_order: i,
  })),
  ["slug"],
);

out += upsert(
  "resources",
  resources.map((r, i) => ({
    id: r.id,
    title: r.title,
    description: r.description,
    type: r.type,
    publisher: r.publisher,
    url: r.url,
    difficulty: r.difficulty,
    cost: r.cost,
    cost_note: r.costNote ?? null,
    language: r.language,
    citation: r.citation ?? null,
    added_at: r.addedAt,
    verified: r.verified,
    sort_order: i,
  })),
  ["id"],
);

out += upsert(
  "topic_resources",
  resources.flatMap((r) => r.topics.map((topic) => ({ topic_slug: topic, resource_id: r.id }))),
  ["topic_slug", "resource_id"],
);

out += upsert(
  "learning_paths",
  learningPaths.map((p, i) => ({
    slug: p.slug,
    title: p.title,
    description: p.description,
    icon: p.icon,
    difficulty: p.difficulty,
    duration: p.duration,
    outcome: p.outcome,
    skills: p.skills,
    featured: Boolean(p.featured),
    sort_order: i,
  })),
  ["slug"],
);

out += upsert(
  "learning_path_stages",
  learningPaths.flatMap((p) =>
    p.stages.map((s, position) => ({
      path_slug: p.slug,
      stage_id: s.id,
      position,
      title: s.title,
      description: s.description,
      skills: s.skills,
      resource_ids: s.resources,
      exercise: s.exercise,
      project_slug: s.project ?? null,
    })),
  ),
  ["path_slug", "stage_id"],
);

out += upsert(
  "projects",
  projects.map((p, i) => ({
    slug: p.slug,
    title: p.title,
    category: p.category,
    difficulty: p.difficulty,
    duration: p.duration,
    description: p.description,
    technologies: p.technologies,
    skills: p.skills,
    requirements: p.requirements,
    steps: p.steps,
    outcome: p.outcome,
    topics: p.topics,
    resource_ids: p.resources,
    github_url: p.githubUrl ?? null,
    featured: Boolean(p.featured),
    sort_order: i,
  })),
  ["slug"],
);

out += "commit;\n";

const target = join(process.cwd(), "supabase", "seed.sql");
writeFileSync(target, out);
console.log(
  `Wrote ${target}\n  ${topics.length} topics, ${resources.length} resources, ${learningPaths.length} paths, ${projects.length} projects`,
);
