import type { Project } from "@/types";

/**
 * Practical projects. These are project briefs written for NEXUS: they describe
 * what to build and how, and link to real resources. `githubUrl` is only set
 * when a real, verified starter repository exists.
 */

type Pair = [title: string, description: string];
type ProjectInput = Omit<Project, "steps"> & { steps: Pair[] };

function project({ steps, ...rest }: ProjectInput): Project {
  return { ...rest, steps: steps.map(([title, description]) => ({ title, description })) };
}

