import type { Topic } from "@/types";

/**
 * All NEXUS topics.
 * To keep the file readable, concepts and roadmap steps are written as
 * [title, description] pairs and converted by the `topic()` helper.
 * See CONTENT_GUIDE.md for how to add a topic.
 */

type Pair = [title: string, description: string];
type TopicInput = Omit<Topic, "coreConcepts" | "roadmap"> & { concepts: Pair[]; steps: Pair[] };

function topic({ concepts, steps, ...rest }: TopicInput): Topic {
  return {
    ...rest,
    coreConcepts: concepts.map(([title, description]) => ({ title, description })),
    roadmap: steps.map(([title, description]) => ({ title, description })),
  };
}

